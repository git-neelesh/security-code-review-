"""SummaryDecisionAgent: Presents the security analysis report and triggers Human-in-the-Loop approval."""

from google.adk.agents import LlmAgent
from google.adk.models.google_llm import Gemini
from google.genai import types

from fetch_status import skip_agent_after_failed_commit_fetch
from tools import approval_function_tool

MODEL_NAME = "gemini-3.5-flash-lite"

retry_config = types.HttpRetryOptions(
    attempts=5,
    exp_base=7,
    initial_delay=1,
    http_status_codes=[429, 500, 503, 504],
)


def summary_decision_agent() -> LlmAgent:
    """Creates the agent that presents the security report and triggers Human-in-the-Loop approval."""
    return LlmAgent(
        name="SummaryDecisionAgent",
        model=Gemini(model=MODEL_NAME, retry_options=retry_config),
        description="Presents the security analysis report to the user and requests approval to create a GitHub issue.",
        before_agent_callback=skip_agent_after_failed_commit_fetch,
        instruction="""You are the Security Review Coordinator responsible for human-in-the-loop sign-off.
Read the security analysis report generated by the previous agent:
{security_analysis_report}

Your responsibilities:
1. Call the `request_security_issue_approval` tool with:
   - `repo_name`: The repository name (`owner/repo`) from the report
   - `commit_id`: The commit ID analyzed
   - `issue_title`: The proposed GitHub issue title from the report
   - `severity_summary`: A 1-2 sentence summary of the findings and overall risk level
2. If the tool returns `status == "pending"`, display the security analysis report clearly to the user and let them know that execution is paused waiting for their approval to create a GitHub issue.
3. Once the tool resumes and returns `status == "approved"` or `status == "rejected"`, record the final decision (`APPROVED` or `REJECTED`), the `repo_name`, `commit_id`, and `issue_title` clearly so the next agent (`IssueReportAgent`) can act on it.
""",
        tools=[approval_function_tool],
        output_key="summary_decision_output",
    )
